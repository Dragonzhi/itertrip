/* Actual React/history + standalone export, offline jsdom; not physical device testing. */
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { JSDOM } from 'jsdom';
import { build } from 'esbuild';
const dir = path.resolve('test-artifacts/m26');
const fixture = JSON.parse(await fs.readFile(path.join(dir, 'route.json'), 'utf8'));
const dom = new JSDOM('<div id="root"></div>', { url: 'http://itertrip.test/', pretendToBeVisual: true });
const w = dom.window;
for (const k of ['window', 'document', 'navigator', 'HTMLElement', 'Element', 'Node', 'SVGElement', 'HTMLDialogElement', 'localStorage', 'history', 'location', 'getComputedStyle']) Object.defineProperty(globalThis, k, { configurable: true, value: k === 'window' ? w : w[k] });
globalThis.requestAnimationFrame = w.requestAnimationFrame.bind(w); globalThis.cancelAnimationFrame = w.cancelAnimationFrame.bind(w);
w.SVGSVGElement.prototype.createSVGRect = () => ({}); w.HTMLElement.prototype.scrollIntoView = () => {};
w.matchMedia = () => ({ matches: false, addEventListener() {}, removeEventListener() {}, addListener() {}, removeListener() {} });
class Observer { observe() {} unobserve() {} disconnect() {} }
globalThis.IntersectionObserver = globalThis.ResizeObserver = Observer;
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
localStorage.setItem('itertrip:route', JSON.stringify(fixture));
const bundle = await build({ entryPoints: ['src/App.tsx'], bundle: true, write: false, format: 'esm', platform: 'browser', jsx: 'automatic', loader: { '.css': 'empty' }, external: ['react', 'react-dom', 'react-dom/*'], define: { 'import.meta.env': '{}' } });
const file = path.join(dir, 'app-dom.mjs'); await fs.writeFile(file, bundle.outputFiles[0].text);
const React = await import('react'), { act } = React, { createRoot } = await import('react-dom/client');
const { default: App } = await import(pathToFileURL(file).href);
const root = createRoot(document.getElementById('root'));
await act(async () => root.render(React.createElement(App)));
const byText = text => { const b = [...document.querySelectorAll('button')].find(b => b.textContent.trim() === text); assert.ok(b, text); return b; };
const click = async b => act(async () => b.dispatchEvent(new w.MouseEvent('click', { bubbles: true })));
const change = async (select, value) => act(async () => { select.value = value; select.dispatchEvent(new w.Event('change', { bubbles: true })); });
const saved = () => JSON.parse(localStorage.getItem('itertrip:route'));
const response = body => ({ results: body.edges.map(e => ({ signature: e.signature, options: ['walk', 'bus', 'car'].map(mode => ({ mode, status: 'ok', duration_s: mode === 'walk' ? 600 : 300, distance_m: 800, walking_m: mode === 'walk' ? 800 : 0, fee_yuan: mode === 'walk' ? 0 : null, queried_at: new Date().toISOString(), source: 'amap', source_url: '' })) })), stats: { calls: 3, cache_hits: 0, reason: '', deduplicated: 0, budget: 24, elapsed_ms: 1 } });
let pending;
globalThis.fetch = async (_url, options) => new Promise(resolve => { pending = () => resolve({ ok: true, json: async () => response(JSON.parse(options.body)) }); });
await click(byText('比较三种方式'));
const originalMode = saved().days[0].traffic_mode;
await change(document.querySelector('[aria-label="第1天默认交通方式"]'), 'car');
await act(async () => pending());
assert.equal(saved().days[0].transport[0].snapshot, undefined, 'old response cannot overwrite route after edit');
assert.ok(document.body.textContent.includes('已取消旧交通查询'));
await click(byText('↩ 撤销'));
assert.equal(saved().days[0].traffic_mode, originalMode);
globalThis.fetch = async (_url, options) => ({ ok: true, json: async () => response(JSON.parse(options.body)) });
await click(byText('比较三种方式'));
assert.ok(saved().days[0].transport[0].snapshot);
assert.ok(document.body.textContent.includes('公交约 5 分钟'));
await click(byText('比较三种方式'));
assert.ok(document.body.textContent.includes('交通查询返回'), 'repeat cached result must not leave loading text');
await change(document.querySelector('[aria-label="前往人民公园的交通方式"]'), 'walk');
assert.equal(saved().days[0].transport[0].mode, 'walk');
await click(byText('↩ 撤销'));
assert.equal(saved().days[0].transport[0].mode, 'bus');
await click(byText('↪ 重做'));
assert.equal(saved().days[0].transport[0].mode, 'walk');
const queried = saved();
globalThis.fetch = async () => { throw new Error('模拟网络中断'); };
await click(byText('比较三种方式'));
assert.equal(saved().days[0].transport[0].snapshot.options[0].status, 'unknown', 'network failure does not keep old metrics as current');
await click(byText('↩ 撤销'));
assert.equal(saved().days[0].transport[0].snapshot.options[0].status, 'ok');
await act(async () => root.unmount());
const core = globalThis.IterTripTransport;
assert.ok(core.summary(queried, 0).known === 1);
// Replace the fixture data with an actual query snapshot and run embedded scripts, no Leaflet.
let html = await fs.readFile(path.join(dir, 'export.html'), 'utf8');
html = html.replace(/const TRIP = [\s\S]*?;\r?\nIterTripTransport.normalize\(TRIP\);/, () => 'const TRIP = ' + JSON.stringify(queried) + ';\nIterTripTransport.normalize(TRIP);');
const exported = new JSDOM(html, { runScripts: 'dangerously', url: 'http://export.test/' });
assert.ok(exported.window.document.querySelector('[data-testid="export-transport"]'));
assert.ok(exported.window.document.body.textContent.includes('步行约 10 分钟'));
assert.ok(exported.window.document.body.textContent.includes('费用小计'));
exported.window.close(); dom.window.close();
console.log('M26 React integration passed: query, stale response, modes, undo/redo and standalone snapshots');
