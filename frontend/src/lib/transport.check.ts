import { normalizeRoute, transport } from './transport.ts';
import { visits } from './outing.ts';
import type { RouteJSON, TransportOption } from '../types/route';
const equal = (a: unknown, b: unknown) => { if (JSON.stringify(a) !== JSON.stringify(b)) throw new Error(JSON.stringify([a, b])); };
const ok = (v: unknown) => { if (!v) throw new Error('assertion failed'); };
const p = { name: '武侯祠', lat: 30.64, lng: 104.05, source: 'user', confidence: 'high' };
const h = { ...p, name: '酒店A', lng: 104.06 };
const route: RouteJSON = normalizeRoute({ trip: { title: '测试', destination: '成都', days: 2 }, days: [
  { day: 1, places: [p, { ...p, name: '锦里', lng: 104.052 }], hotel: h },
  { day: 2, places: [{ ...p, name: '人民公园', lat: 30.66 }], hotel: { ...h, name: '酒店B', lng: 104.08 } },
] });
equal(transport.legs(route, 0).map(e => [e.from.name, e.to.name]), [['武侯祠', '锦里'], ['锦里', '酒店A']]);
equal(transport.legs(route, 1).map(e => [e.from.name, e.to.name]), [['酒店A', '人民公园'], ['人民公园', '酒店B']]);
equal(route.days[0].start_from_hotel, false);
ok(new Set(route.days.flatMap(d => [...d.places, d.hotel!]).map(p => p.id)).size === 5);
const edge = transport.legs(route, 0)[0];
const option: TransportOption = { mode: 'walk', status: 'ok', duration_s: 600, walking_m: 800, distance_m: 800, fee_yuan: null, queried_at: new Date().toISOString(), source: 'amap', source_url: '' };
route.days[0].transport![0].snapshot = { signature: transport.sign(edge), options: [option] };
route.days[0].transport![0].buffer_min = 10;
let summary = transport.summary(route, 0);
equal([summary.seconds, summary.known, summary.feeKnown, summary.buffer], [600, 1, 0, 10]);
const savedId = visits(route)[0].id;
const reordered = normalizeRoute({ ...route, days: [{ ...route.days[0], places: [...route.days[0].places].reverse() }, route.days[1]] }, route);
equal(reordered.days[0].places[1].id, route.days[0].places[0].id);
equal(visits(reordered)[1].id, savedId);
ok(!reordered.days[0].transport!.some(s => s.snapshot));
const moved = JSON.parse(JSON.stringify(route)) as RouteJSON;
moved.days[0].places[0].lat += .001;
ok(!normalizeRoute(moved, route).days[0].transport![0].snapshot);
const city = JSON.parse(JSON.stringify(route)) as RouteJSON;
city.days[0].places[0].source = 'city';
ok(!normalizeRoute(city, route).days[0].transport![0].snapshot);
ok(!transport.usable(city.days[0].places[0]));
const pending = JSON.parse(JSON.stringify(route)) as RouteJSON;
pending.days[0].places[0].note = '门口集合【坐标待确认】';
pending.days[0].places[0].source = 'llm'; pending.days[0].places[0].confidence = 'low';
const confirmed = JSON.parse(JSON.stringify(pending)) as RouteJSON;
confirmed.days[0].places[0].lat += .001; confirmed.days[0].places[0].source = 'user'; confirmed.days[0].places[0].confidence = 'high';
ok(transport.usable(normalizeRoute(confirmed, pending).days[0].places[0]));
route.days[0].transport![0].snapshot!.options[0].queried_at = '2000-01-01T00:00:00Z';
equal(transport.summary(route, 0).known, 0);
const dup = normalizeRoute({ ...route, days: [{ day: 1, places: [p, p] }] });
ok(dup.days[0].places[0].id !== dup.days[0].places[1].id);
const inserted = JSON.parse(JSON.stringify(route)) as RouteJSON;
inserted.days[0].places.unshift({ ...inserted.days[0].places[0], id: undefined });
const insertedNorm = normalizeRoute(inserted, route);
equal(insertedNorm.days[0].places[1].id, route.days[0].places[0].id);
ok(insertedNorm.days[0].places[0].id !== insertedNorm.days[0].places[1].id);
equal(normalizeRoute(route).days[1].hotel!.id, route.days[1].hotel!.id);
console.log('M26 identity, hotel transfer, invalidation, progress and partial summary contracts passed');
